    // ── 折扣碼（discount_codes/{CODE}，管理員可編輯）──────────────
    // effect：pro / admin；maxRedemptions：發行數量（null=無限）；redemptions：已兌換數；expiresAt：使用效期 epoch millis（null=永久）。
    data class DiscountCode(
        val code: String,
        val effect: String,
        val note: String?,
        val maxRedemptions: Int? = null,
        val redemptions: Int = 0,
        val expiresAt: Long? = null
    )

    /** 兌換結果：不存在 / 存在但無效（過期或額滿）/ 成功並回傳效用。 */
    sealed class RedeemOutcome {
        object NotFound : RedeemOutcome()
        object Invalid : RedeemOutcome()
        data class Ok(val effect: String) : RedeemOutcome()
    }

    private fun discountCodeFromDoc(d: com.google.firebase.firestore.DocumentSnapshot) = DiscountCode(
        code = d.id,
        effect = d.getString("effect") ?: "pro",
        note = d.getString("note"),
        maxRedemptions = d.getLong("maxRedemptions")?.toInt(),
        redemptions = (d.getLong("redemptions") ?: 0L).toInt(),
        expiresAt = d.getLong("expiresAt")
    )

    suspend fun fetchDiscountCodes(): Result<List<DiscountCode>> = withContext(Dispatchers.IO) {
        runCatching {
            Tasks.await(db.collection("discount_codes").get()).documents
                .map { discountCodeFromDoc(it) }.sortedBy { it.code }
        }
    }


    /** 兌換雲端折扣碼：交易內檢查效期與發行數量，通過則原子遞增 redemptions 並回傳效用。 */
    suspend fun redeemDiscountCode(code: String): RedeemOutcome = withContext(Dispatchers.IO) {
        runCatching {
            val ref = db.collection("discount_codes").document(code.trim().uppercase())
            Tasks.await(db.runTransaction { txn ->
                val d = txn.get(ref)
                if (!d.exists()) return@runTransaction RedeemOutcome.NotFound
                val expiresAt = d.getLong("expiresAt")
                if (expiresAt != null && System.currentTimeMillis() > expiresAt) return@runTransaction RedeemOutcome.Invalid
                val max = d.getLong("maxRedemptions")
                val used = d.getLong("redemptions") ?: 0L
                if (max != null && used >= max) return@runTransaction RedeemOutcome.Invalid
                txn.update(ref, "redemptions", used + 1)
                RedeemOutcome.Ok(d.getString("effect") ?: "pro")
            })
        }.getOrDefault(RedeemOutcome.NotFound)
    }

    /** 新增 / 編輯折扣碼。merge 寫入設定欄位，保留既有的 redemptions（已兌換數）。 */
    suspend fun saveDiscountCode(
        code: String, effect: String, note: String?,
        maxRedemptions: Int? = null, expiresAt: Long? = null
    ): Result<Unit> = withContext(Dispatchers.IO) {
        runCatching {
            Tasks.await(
                db.collection("discount_codes").document(code.trim().uppercase())
                    .set(
                        mapOf(
                            "effect" to effect,
                            "note" to note,
                            "maxRedemptions" to maxRedemptions?.toLong(),
                            "expiresAt" to expiresAt,
                            "updatedAt" to System.currentTimeMillis()
                        ),
                        com.google.firebase.firestore.SetOptions.merge()
                    )
            )
            Unit
        }
    }

    suspend fun deleteDiscountCode(code: String): Result<Unit> = withContext(Dispatchers.IO) {
        runCatching {
            Tasks.await(db.collection("discount_codes").document(code.trim().uppercase()).delete())
            Unit
        }
    }

    // ── 官方通知（announcements/{id}）：管理員發布、所有使用者可讀 ──────────
    data class Announcement(val id: String, val title: String, val body: String, val createdAt: Long, val createdBy: String?)

    /** 管理員發布一則官方通知給所有使用者。 */
    /**
     * 記下這台裝置的 FCM token。
     *
     * 為什麼需要：全體公告走 topic 推播就夠了，但**指定對象**的公告沒辦法用 topic
     * ——topic 是「誰訂閱誰就收得到」，沒有辦法只送給其中三個人。
     * 要指定對象就得知道那些人的裝置 token。
     *
     * 存成陣列：一個人可能有手機 + 平板。用 arrayUnion 不用覆蓋，
     * 否則在 A 裝置登入就會把 B 裝置的 token 洗掉，B 從此收不到。
     */
    suspend fun registerPushToken(token: String) = withContext(Dispatchers.IO) {
        val u = uid() ?: return@withContext
        if (token.isBlank()) return@withContext
        runCatching {
            Tasks.await(
                db.collection("users").document(u).set(
                    mapOf("fcmTokens" to com.google.firebase.firestore.FieldValue.arrayUnion(token)),
                    com.google.firebase.firestore.SetOptions.merge()
                )
            )
        }.onFailure { android.util.Log.w("FirestoreService", "registerPushToken failed", it) }
        Unit
    }

    /**
     * 把舊公告補上 `targetUids: []`（＝全體）。
     *
     * 為什麼需要：收信匣改成「查全體公告 + 查指定給我的」兩段之後，
     * 沒有這個欄位的舊公告兩段都查不到，升級之後會整批消失。
     *
     * 只有管理員寫得動 announcements，所以放在後台開啟時跑；
     * 已經有欄位的不寫回，所以重複執行沒有成本。
     */
    suspend fun backfillAnnouncementTargets(): Result<Int> = withContext(Dispatchers.IO) {
        runCatching {
            val docs = Tasks.await(db.collection("announcements").get()).documents
            var fixed = 0
            docs.forEach { d ->
                if (d.get("targetUids") != null) return@forEach
                runCatching {
                    Tasks.await(
                        d.reference.set(
                            mapOf("targetUids" to emptyList<String>()),
                            com.google.firebase.firestore.SetOptions.merge()
                        )
                    )
                    fixed++
                }
            }
            fixed
        }.onFailure { android.util.Log.w("FirestoreService", "backfillAnnouncementTargets failed", it) }
    }

    /** email → uid。發公告給特定人時用；查不到的回傳在 missing 裡，不要靜悄悄少送。 */
    suspend fun resolveUidsByEmail(emails: List<String>): Result<Pair<List<String>, List<String>>> =
        withContext(Dispatchers.IO) {
            runCatching {
                val wanted = emails.map { it.trim().lowercase() }.filter { it.isNotBlank() }.distinct()
                if (wanted.isEmpty()) return@runCatching emptyList<String>() to emptyList()
                val docs = Tasks.await(db.collection("users").get()).documents
                val found = mutableListOf<String>()
                val hit = mutableSetOf<String>()
                docs.forEach { d ->
                    val mail = d.getString("email")?.trim()?.lowercase() ?: return@forEach
                    if (mail in wanted) { found += d.id; hit += mail }
                }
                found to wanted.filterNot { it in hit }
            }
        }

