    /**
     * 刪除雲端沒被任何場次引用的照片。**只能由使用者按下確認後呼叫。**
     *
     * 刻意要求傳入 [expected]（確認對話框上顯示的張數）：若實際數量跟當時看到的不一樣
     * （例如中途在別的裝置改過），就整個放棄。使用者確認的是「刪這 N 張」，
     * 不是「刪掉任何現在算出來是孤兒的東西」。
     */
    suspend fun deleteOrphanImages(concerts: List<Concert>, expected: Int): Result<Int> =
        withContext(Dispatchers.IO) {
            val u = uid() ?: return@withContext Result.failure(IllegalStateException("尚未登入"))
            // 本機一場都沒有時不做：剛重灌還沒還原的狀態下，雲端全部都會被算成孤兒。
            if (concerts.isEmpty()) {
                return@withContext Result.failure(IllegalStateException("本機沒有任何場次，為安全起見不執行"))
            }
            runCatching {
                val col = db.collection("users").document(u).collection("images")
                val wanted = concerts.flatMap { it.allImageUris() }.distinct().map { imageKey(it) }.toSet()
                val orphans = Tasks.await(col.get()).documents.filter { it.id !in wanted }
                if (orphans.size != expected) {
                    error("雲端狀態已變動（現在是 ${orphans.size} 張，你確認的是 $expected 張），請重新確認")
                }
                commitBatched(orphans.map { d -> { b: com.google.firebase.firestore.WriteBatch -> b.delete(d.reference) } })
                orphans.size
            }
        }

    /**
     * 還原時呼叫：把裝置上已讀不到的圖片 URI（換手機 / 重灌後原相簿 URI 失效）
     * 換成從雲端下載回 filesDir 的本機檔案。讀得到的 URI 原樣保留。
     */
    /** 本機讀不到就是 false（權限被收回 / 使用者在相簿搬移或刪除原圖）。 */
    private fun readableUri(uriStr: String): Boolean = runCatching {
        context.contentResolver.openInputStream(android.net.Uri.parse(uriStr))?.use { true } ?: false
    }.getOrDefault(false)

    suspend fun materializeImages(concerts: List<Concert>): List<Concert> = withContext(Dispatchers.IO) {
        val u = uid() ?: return@withContext concerts
        val col = db.collection("users").document(u).collection("images")
        val dir = java.io.File(context.filesDir, "restored_images").apply { mkdirs() }
        val cache = mutableMapOf<String, String?>()

        fun resolve(uriStr: String?): String? {
            if (uriStr.isNullOrBlank() || readableUri(uriStr)) return uriStr
            return cache.getOrPut(uriStr) {
                runCatching {
                    // 檔名用照片的身分（見 ConcertImageMerge.identity）：這張若本來就是別台還原回來的檔，
                    // 沿用同一個名字，三台裝置之間才認得出是同一張，不會被當成新照片重複合併。
                    val id = ConcertImageMerge.identity(uriStr)
                    val file = java.io.File(dir, "$id.jpg")
                    if (!file.exists()) {
                        val blob = listOf(imageKey(uriStr), id).distinct().firstNotNullOfOrNull { key ->
                            Tasks.await(col.document(key).get()).getBlob("data")
                        } ?: return@runCatching null
                        file.writeBytes(blob.toBytes())
                    }
                    android.net.Uri.fromFile(file).toString()
                }.getOrNull()
            } ?: uriStr // 雲端也沒有就保留原字串，至少不弄丟資訊
        }

        concerts.map { c ->
            c.copy(
                photoUri = resolve(c.photoUri),
                seatMapUri = resolve(c.seatMapUri),
                photoUris = c.photoUris.map { resolve(it) ?: it },
                timetableUris = c.timetableUris.map { resolve(it) ?: it },
                dayCovers = c.dayCovers.map { if (it.isBlank()) it else (resolve(it) ?: it) }
            )
        }
    }

