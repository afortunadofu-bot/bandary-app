    /**
     * 排行榜的「重疊比對資料」。刻意分成子文件而不是塞在名次那筆裡：
     * 排行榜列表一次要讀所有人的資料，把陣列放在同一份文件會讓列表變得很重
     * （Firestore 用戶端 SDK 讀文件是整份回傳，沒辦法只挑欄位）。
     * 點進某個人才讀他這一份。與 shared_calendars 的名片／private payload 是同一套做法。
     *
     * showKeys 存的是雜湊、不是「日期＋場館」原文：
     * 別人無法從這份資料列舉你看過哪些場次，但因為你知道自己的場次、可以算出自己的雜湊，
     * 所以系統仍算得出「你們重疊幾場」。也就是**你只會知道跟自己重疊的部分**。
     */
    private fun leaderboardDetailRef(year: Int, uid: String) =
        db.collection("yearly_leaderboard").document(year.toString())
            .collection("entries").document(uid).collection("detail").document("payload")

    /** 把字串轉成短雜湊（比對用，不可逆推原文）。 */
    fun overlapKey(raw: String): String {
        val norm = raw.trim().lowercase()
        val md = java.security.MessageDigest.getInstance("SHA-256")
        return md.digest(norm.toByteArray()).take(8)
            .joinToString("") { "%02x".format(it) }
    }

