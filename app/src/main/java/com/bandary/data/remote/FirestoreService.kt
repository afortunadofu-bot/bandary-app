    /**
     * 宣告 / 變更自己的好友代碼。以 transaction 保證全域唯一：handles/{小寫} → {uid}。
     * 變更時釋放舊的代碼，並把新代碼同步到 users/{uid} 與已發布的 shared_calendars/{uid}。
     */
    suspend fun claimHandle(rawHandle: String): Result<Unit> = withContext(Dispatchers.IO) {
        val u = uid() ?: return@withContext Result.failure(IllegalStateException("尚未登入"))
        val handle = rawHandle.trim().removePrefix("@")
        val lower = handle.lowercase()
        if (!Regex("^[a-z0-9_]{3,20}$").matches(lower)) {
            return@withContext Result.failure(IllegalArgumentException("好友代碼需 3–20 字，僅限英文、數字與底線"))
        }
        runCatching {
            Tasks.await(db.runTransaction { txn ->
                val handleRef = db.collection("handles").document(lower)
                val userRef = db.collection("users").document(u)
                // 所有讀取需在寫入之前
                val handleSnap = txn.get(handleRef)
                val userSnap = txn.get(userRef)
                val ownerUid = handleSnap.getString("uid")
                if (handleSnap.exists() && ownerUid != u) {
                    throw com.google.firebase.firestore.FirebaseFirestoreException(
                        "這組好友代碼已經有人用了",
                        com.google.firebase.firestore.FirebaseFirestoreException.Code.ABORTED
                    )
                }
                val oldHandle = userSnap.getString("handle")
                txn.set(handleRef, mapOf("uid" to u, "handle" to handle, "claimedAt" to System.currentTimeMillis()))
                if (oldHandle != null && oldHandle.lowercase() != lower) {
                    txn.delete(db.collection("handles").document(oldHandle.lowercase()))
                }
                txn.set(
                    userRef,
                    mapOf("handle" to handle, "email" to currentEmail()),
                    com.google.firebase.firestore.SetOptions.merge()
                )
                null
            })
            // 同步到共享日曆（若已發布過才有此 doc；merge 不會建立多餘欄位以外的東西）
            runCatching {
                Tasks.await(
                    db.collection("shared_calendars").document(u)
                        .set(mapOf("handle" to handle), com.google.firebase.firestore.SetOptions.merge())
                )
            }
            Unit
        }
    }

    /**
     * 確保我有好友代碼：沒有就自動配一個，撞號就補隨機數字重試。
     *
     * 全 App 只讓使用者取一個名字（暱稱）。好友代碼不是第二個名字，而是別人搜尋你用的 ID，
     * 所以第一次不問使用者、登入後自己補上；想改成好記的再自己改（claimHandle）。
     */
    suspend fun ensureHandle(): Result<String> = withContext(Dispatchers.IO) {
        uid() ?: return@withContext Result.failure(IllegalStateException("尚未登入"))
        myHandle().getOrNull()?.takeIf { it.isNotBlank() }?.let { return@withContext Result.success(it) }
        val base = suggestedHandleBase()
        var last: Throwable? = null
        repeat(8) { attempt ->
            // 第一次直接用推導出的代碼；之後每次都換一組隨機尾數，避免一直撞同一個人。
            val candidate = if (attempt == 0) base else base.take(15).trimEnd('_') + (100..9999).random()
            claimHandle(candidate)
                .onSuccess { return@withContext Result.success(candidate) }
                .onFailure { last = it }
        }
        Result.failure(last ?: IllegalStateException("無法配發好友代碼"))
    }

