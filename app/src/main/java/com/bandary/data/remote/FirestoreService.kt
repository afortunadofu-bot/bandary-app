    fun accountDisplayName(): String =
        auth.currentUser?.displayName?.takeIf { it.isNotBlank() }
            ?: auth.currentUser?.email?.substringBefore("@") ?: "我"

    /**
     * 依暱稱（其次 Google 帳號名稱、email 前綴）推導一個合法的好友代碼：轉小寫、非 [a-z0-9] 一律轉底線、去掉頭尾與重複底線。
     * 中文暱稱清完可能太短，就往下退，再不行給 user+隨機數，確保永遠給得出可用的預設值。
     */
    fun suggestedHandleBase(): String {
        // 洗字串的規則抽到 domain 層並有測試釘住，才不會跟網頁版那份實作各自漂移。
        val sources = listOf(
            preferredDisplayName,
            auth.currentUser?.displayName,
            auth.currentUser?.email?.substringBefore("@")
        )
        sources.forEach { src ->
            val cleaned = com.bandary.domain.model.cleanHandleSegment(src ?: "")
            if (cleaned.length >= 3) return cleaned.take(20)
        }
        return "user${(1000..9999).random()}"
    }
