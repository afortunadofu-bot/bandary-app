    // ── 圖片備份（壓縮後以 Firestore Blob 存 users/{uid}/images/{sha1(uri)}）──
    private fun Concert.allImageUris(): List<String> =
        (listOfNotNull(photoUri, seatMapUri, pickupShotUri) + photoUris + timetableUris + dayCovers)
