/**
 * 雲端的開賣時間 → [SaleTime]。網頁與 App 都寫成 `[{label, at}]`。
 * [legacy] 是舊的單一 saleStartAt 字串：只有在沒有 saleTimes 時才拿來補一筆，
 * 否則同一筆開賣時間會重複出現（新舊欄位是刻意並存的）。
 */
private fun saleTimesFromCloud(raw: Any?, legacy: Any?): List<SaleTime> {
    val list = (raw as? List<*>)?.mapNotNull { item ->
        val map = item as? Map<*, *> ?: return@mapNotNull null
        val at = (map["at"] as? String)?.let { runCatching { LocalDateTime.parse(it) }.getOrNull() }
        at?.let { SaleTime(map["label"] as? String ?: "", it) }
    }.orEmpty()
    if (list.isNotEmpty()) return list
    val old = (legacy as? String)?.let { runCatching { LocalDateTime.parse(it) }.getOrNull() }
    return old?.let { listOf(SaleTime("", it)) }.orEmpty()
}

