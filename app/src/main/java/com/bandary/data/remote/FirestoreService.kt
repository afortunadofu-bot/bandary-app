    /** 接受好友請求：一次 batch 雙寫（我←→對方），並刪掉請求。 */
    suspend fun acceptFriendRequest(req: com.bandary.domain.model.FriendRequest): Result<Unit> = withContext(Dispatchers.IO) {
        val myUid = uid() ?: return@withContext Result.failure(IllegalStateException("尚未登入"))
        runCatching {
            val myHandle = Tasks.await(db.collection("users").document(myUid).get()).getString("handle") ?: ""
            val batch = db.batch()
            val meToThem = Friend(uid = req.fromUid, email = req.fromEmail, displayName = req.fromDisplayName, handle = req.fromHandle)
            batch.set(
                db.collection("users").document(myUid).collection("friends").document(req.fromUid),
                meToThem.toCloudMap()
            )
            val themToMe = Friend(uid = myUid, email = currentEmail()?.lowercase() ?: "", displayName = currentDisplayName(), handle = myHandle)
            batch.set(
                db.collection("users").document(req.fromUid).collection("friends").document(myUid),
                themToMe.toCloudMap()
            )
            batch.delete(
                db.collection("users").document(myUid).collection("friend_requests").document(req.fromUid)
            )
            Tasks.await(batch.commit())
            Unit
        }
    }

