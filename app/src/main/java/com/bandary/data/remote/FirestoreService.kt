    private fun imageKey(uri: String): String =
        java.security.MessageDigest.getInstance("SHA-1")
            .digest(uri.toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }

    /** 讀本機 URI、壓縮成 ≤ 900KB 的 JPEG（Firestore 單文件 1MB 上限）。讀不到回 null。 */
    private fun compressImage(uriStr: String): ByteArray? = runCatching {
        val uri = android.net.Uri.parse(uriStr)
        val bounds = android.graphics.BitmapFactory.Options().apply { inJustDecodeBounds = true }
        // 注意：inJustDecodeBounds = true 時 decodeStream 一定回 null，只會把尺寸寫進 bounds。
        // 這裡原本寫成 `openInputStream(uri)?.use { decodeStream(...) } ?: return null`，
        // 那個 elvis 對每一張圖都成立，等於每次都在這行 return null——
        // 所有照片與頭貼從來沒有真的上傳過（實機：133 張全被回報成「找不到原檔」）。
        // 要判斷讀得到與否，看的是 openInputStream 本身和解出來的尺寸。
        val bounded = context.contentResolver.openInputStream(uri) ?: return null
        bounded.use { android.graphics.BitmapFactory.decodeStream(it, null, bounds) }
        if (bounds.outWidth <= 0 || bounds.outHeight <= 0) return null
        var sample = 1
        while (bounds.outWidth / sample > 1600 || bounds.outHeight / sample > 1600) sample *= 2
        val opts = android.graphics.BitmapFactory.Options().apply { inSampleSize = sample }
        val decoded = context.contentResolver.openInputStream(uri)?.use {
            android.graphics.BitmapFactory.decodeStream(it, null, opts)
        } ?: return null
        // BitmapFactory 不看 EXIF：直拍的照片解出來是躺著的，重壓成 JPEG 後方向資訊也沒了，
        // 於是雲端存的就是顛倒的圖（實機回報）。解完立刻依 EXIF 轉正。
        val bmp = com.bandary.data.util.ImageStore.applyExifRotation(context, uri, decoded)
        if (bmp !== decoded) decoded.recycle()
        var quality = 85
        var bytes: ByteArray
        do {
            val bos = java.io.ByteArrayOutputStream()
            bmp.compress(android.graphics.Bitmap.CompressFormat.JPEG, quality, bos)
            bytes = bos.toByteArray()
            quality -= 15
        } while (bytes.size > 900_000 && quality >= 25)
        // 降畫質還是塞不進 Firestore 的一份文件（1MB）時，把尺寸再對半縮後重壓。
        // 以前這種圖直接回 null，等於那張照片永遠備份不上去，而且畫面上只會說「讀不到」。
        var scaled = bmp
        while (bytes.size > 900_000 && scaled.width > 400 && scaled.height > 400) {
            val next = android.graphics.Bitmap.createScaledBitmap(scaled, scaled.width / 2, scaled.height / 2, true)
            if (scaled !== bmp) scaled.recycle()
            scaled = next
            val bos = java.io.ByteArrayOutputStream()
            scaled.compress(android.graphics.Bitmap.CompressFormat.JPEG, 80, bos)
            bytes = bos.toByteArray()
        }
        if (scaled !== bmp) scaled.recycle()
        bmp.recycle()
        if (bytes.size > 1_000_000) null else bytes
    }.getOrNull()

    /**
     * 備份所有演唱會圖片（封面 / 照片 / 座位圖 / 各日封面）。
     * 鏡像本機：雲端已不再被引用的圖會刪除；已備份過的 URI 跳過不重傳。回傳新上傳張數。
     */
    /**
     * 照片備份結果。以前單張失敗一律當 0 吞掉，整批「成功」卻一張都沒上傳，使用者完全不知道
     * （實機：157 張照片、雲端 0 張）。現在分開回報，畫面上講得出是哪一種問題。
     */
    data class ImageBackupReport(
        val uploaded: Int,
        val alreadyBackedUp: Int,
        val unreadable: Int,
        val failed: Int,
        val firstError: String?,
        /**
         * 雲端有、但目前本機沒有任何場次引用的照片張數。
         *
         * 這些**不會**在備份時被刪掉。它們多半不是垃圾，而是：
         * 本機原檔被相簿刪了、用了「移除讀不到的照片」把欄位清掉、
         * 或這支手機根本還沒還原完。雲端那份是唯一剩下的副本，
         * 要刪只能由使用者自己按、而且要先看到張數。
         */
        val orphanedInCloud: Int = 0
    )

    /**
     * 備份照片。**永遠不刪雲端**（[allowCleanup] 已移除）。
     *
     * 以前這裡會把「雲端有、但本機沒引用」的照片直接刪掉，而且手動備份選
     * 「以本機為準」時預設就會做。實機災情：使用者先用「移除讀不到的照片」
     * 把 50 幾張讀不到的欄位清掉（那功能本來就是設計成這樣），
     * 下一次備份就把雲端那 50 幾張一起刪了，只剩 7 張，而且還原不回來。
     *
     * 備份的語意就是**只增不減**。刪除是另一件事，走 [deleteOrphanImages]，
     * 由使用者看到張數、自己按確認。
     */
    suspend fun backupImages(concerts: List<Concert>): Result<ImageBackupReport> = withContext(Dispatchers.IO) {
        val u = uid() ?: return@withContext Result.failure(IllegalStateException("尚未登入"))
        runCatching {
            val col = db.collection("users").document(u).collection("images")
            val wantedKeys = concerts.flatMap { it.allImageUris() }.distinct().associateBy { imageKey(it) }
            val cloud = Tasks.await(col.get()).documents
            val cloudIds = cloud.map { it.id }.toSet()
            // 只統計、不刪。照片是這個 App 裡最不可復原的東西：
            // 場次資料使用者重打得回來，照片刪掉就沒了。
            val orphaned = cloud.count { it.id !in wantedKeys }
            // 只上傳新圖；壓縮（CPU）+ 上傳（網路）限流並行，取代原本逐張序列處理。
            // Blob 可達 ~900KB 不適合塞進 WriteBatch（10MB/批上限），故用有界並行。
            val toUpload = wantedKeys.filterKeys { it !in cloudIds }.toList()
            val sem = Semaphore(4)
            // 每張的結果：1＝上傳成功、0＝本機讀不到、其餘＝上傳失敗的錯誤訊息。
            val results: List<Any> = coroutineScope {
                toUpload.map { (key, uriStr) ->
                    async {
                        sem.withPermit {
                            val bytes = compressImage(uriStr) ?: return@withPermit 0
                            runCatching {
                                Tasks.await(
                                    col.document(key).set(
                                        mapOf(
                                            "uri" to uriStr,
                                            "data" to com.google.firebase.firestore.Blob.fromBytes(bytes),
                                            "updatedAt" to System.currentTimeMillis()
                                        )
                                    )
                                )
                                1
                            }.getOrElse { e ->
                                android.util.Log.w("FirestoreService", "image upload failed", e)
                                e.message ?: e.javaClass.simpleName
                            }
                        }
                    }
                }.awaitAll()
            }
            ImageBackupReport(
                uploaded = results.count { it == 1 },
                alreadyBackedUp = wantedKeys.size - toUpload.size,
                unreadable = results.count { it == 0 },
                failed = results.count { it is String },
                firstError = results.firstOrNull { it is String } as? String,
                orphanedInCloud = orphaned
            )
        }.onFailure { android.util.Log.w("FirestoreService", "backupImages failed", it) }
    }

