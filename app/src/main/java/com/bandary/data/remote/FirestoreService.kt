    // ── Backup (local → cloud) ────────────────────────────────
    /** 把一串寫入操作以 WriteBatch 分批（每批 ≤ 450 筆）送出，取代逐筆 await——大幅減少往返次數。 */
    private fun commitBatched(ops: List<(com.google.firebase.firestore.WriteBatch) -> Any?>) {
        ops.chunked(450).forEach { chunk ->
            val batch = db.batch()
            chunk.forEach { it(batch) }
            Tasks.await(batch.commit())
        }
    }

    /** 同步結果：要寫回本機的場次（雲端較新或本機沒有），以及實際上傳的筆數。 */
    data class ConcertSync(
        val pulled: List<Concert>,
        val pushed: Int,
        /** 兩邊取多的時，從另一邊補回來的照片張數。 */
        val photosMerged: Int = 0,
        /** 本機照片比雲端少、這次先不推上去的場次數（自動備份才會有）。 */
        val skippedShrink: Int = 0
    )

    /**
     * 同一場兩邊都有、但「比較新的那份照片比較少」時怎麼辦。
     * 以前一律整筆蓋掉，雲端照片就這樣變少。
     */
    enum class ImageSyncMode {
        /** 兩邊取多的：照片合併，雙方都寫成合併後的版本。手動備份的預設。 */
        MERGE,
        /** 以本機為準：照片少了就是少了（使用者確認過才用）。 */
        OVERWRITE,
        /** 本機比較少的先不推，留給下次手動備份時問使用者。自動備份用，不會在背景偷偷刪照片。 */
        KEEP_CLOUD
    }

    /** 備份前預覽：這次備份會讓雲端少掉多少照片。 */
    data class ShrinkPreview(
        val cloudPhotos: Int,
        val localPhotos: Int,
        /** 本機比雲端少照片、而且本機版本比較新（會蓋掉雲端）的場次數與張數。 */
        val concerts: Int,
        val photos: Int
    )

    suspend fun previewShrink(local: List<Concert>): Result<ShrinkPreview> = withContext(Dispatchers.IO) {
        val u = uid() ?: return@withContext Result.failure(IllegalStateException("尚未登入"))
        runCatching {
            val cloud = Tasks.await(db.collection("users").document(u).collection("concerts").get()).documents
                .mapNotNull { d -> d.data?.let(::concertFromMap) }
                .filter { it.deletedAt == null }
                .associateBy { it.id }
            val alive = local.filter { it.deletedAt == null }
            var concerts = 0
            var photos = 0
            alive.forEach { l ->
                val c = cloud[l.id] ?: return@forEach
                if (l.updatedAt < c.updatedAt) return@forEach   // 雲端較新：會拉回本機，不會蓋掉雲端
                val lost = ConcertImageMerge.missingCount(l, c)
                if (lost > 0) { concerts++; photos += lost }
            }
            ShrinkPreview(
                cloudPhotos = cloud.values.sumOf { ConcertImageMerge.images(it).size },
                localPhotos = alive.sumOf { ConcertImageMerge.images(it).size },
                concerts = concerts,
                photos = photos
            )
        }
    }

    /**
     * 演唱會雙向同步（取代原本的鏡像備份）。
     *
     * 舊版是「以本機為準鏡像雲端」——雲端有、本機沒有的一律刪除。那在只有一台裝置時沒問題，
     * 但只要有第二個寫入端（PWA、另一支手機），對方新增的東西會在下一次備份被無聲刪掉。
     *
     * 現在改成逐筆比 updatedAt（last-write-wins）：
     *   • 兩邊都有 → 誰的 updatedAt 大就是誰贏
     *   • 只有本機有 → 上傳
     *   • 只有雲端有且未刪除 → 拉回本機（這就是 PWA 新增的那一筆）
     *   • 只有雲端有但已是墓碑（deletedAt 有值）→ 本機已過期清掉，順手刪掉雲端文件
     *
     * 刪除靠 deletedAt 墓碑傳遞，不再直接刪文件，否則對方會把它當成「新資料」再同步回來。
     */
    suspend fun syncConcerts(
        local: List<Concert>,
        imageMode: ImageSyncMode = ImageSyncMode.KEEP_CLOUD
    ): Result<ConcertSync> = withContext(Dispatchers.IO) {
        val u = uid() ?: return@withContext Result.failure(IllegalStateException("尚未登入"))
        runCatching {
            val userDoc = db.collection("users").document(u)
            // 寫一個父文件標記，讓 users/{uid} 在 Console 看得到，也確認可寫入。
            Tasks.await(
                userDoc.set(
                    mapOf("email" to currentEmail(), "lastBackupAt" to System.currentTimeMillis()),
                    com.google.firebase.firestore.SetOptions.merge()
                )
            )
            val col = userDoc.collection("concerts")
            val cloud = Tasks.await(col.get()).documents
                .mapNotNull { d -> d.data?.let(::concertFromMap) }
                .associateBy { it.id }
            val localById = local.associateBy { it.id }

            val toPush = mutableListOf<Concert>()
            val toPull = mutableListOf<Concert>()
            val toDeleteInCloud = mutableListOf<String>()
            var photosMerged = 0
            var skippedShrink = 0
            // 垃圾桶保留 7 天，與 ConcertRepository.purgeExpiredTrash 同一個界線。
            val trashCutoff = System.currentTimeMillis() - 7L * 24 * 60 * 60 * 1000

            (localById.keys + cloud.keys).forEach { id ->
                val l = localById[id]
                val c = cloud[id]
                if (l != null && c != null) {
                    // 較新的那份照片比較少時，不能直接整筆蓋掉（見 ImageSyncMode）。
                    // 在垃圾桶裡的場次照舊處理：刪除靠墓碑傳遞，不需要合併照片。
                    val bothAlive = l.deletedAt == null && c.deletedAt == null
                    val localWins = l.updatedAt >= c.updatedAt
                    val winner = if (localWins) l else c
                    val loser = if (localWins) c else l
                    val lost = if (bothAlive) ConcertImageMerge.missingCount(winner, loser) else 0
                    when {
                        lost == 0 || imageMode == ImageSyncMode.OVERWRITE -> {
                            // 相等就代表兩邊同步過了，什麼都不用做。
                            if (l.updatedAt > c.updatedAt) toPush += l
                            else if (c.updatedAt > l.updatedAt) toPull += c
                        }
                        imageMode == ImageSyncMode.KEEP_CLOUD && localWins -> skippedShrink++
                        else -> {
                            // 兩邊取多的：合併後的版本同時寫回雲端與本機，兩邊就一致了。
                            val merged = ConcertImageMerge.union(winner, loser)
                            photosMerged += lost
                            toPush += merged
                            toPull += merged
                        }
                    }
                } else if (l != null) {
                    toPush += l
                } else if (c != null) {
                    // 雲端獨有：已過期的墓碑就清掉，否則是別的裝置新增的，拉回來。
                    val tomb = c.deletedAt
                    if (tomb != null && tomb < trashCutoff) toDeleteInCloud += id else toPull += c
                }
            }

            commitBatched(
                toPush.map { c -> { b: com.google.firebase.firestore.WriteBatch -> b.set(col.document(c.id), c.toCloudMap()) } } +
                    toDeleteInCloud.map { id -> { b: com.google.firebase.firestore.WriteBatch -> b.delete(col.document(id)) } }
            )
            ConcertSync(pulled = toPull, pushed = toPush.size, photosMerged = photosMerged, skippedShrink = skippedShrink)
        }.onFailure { android.util.Log.w("FirestoreService", "syncConcerts failed", it) }
    }

