    suspend fun globalStats(maxUsers: Int = 300): Result<GlobalStats> = withContext(Dispatchers.IO) {
        runCatching {
            val users = Tasks.await(db.collection("users").limit(maxUsers.toLong()).get()).documents
            val songArtists = HashMap<String, Int>()
            val songTitles = HashMap<String, Int>()
            val concertArtists = HashMap<String, Int>()
            val cities = HashMap<String, Int>()
            var totalConcerts = 0
            var totalSongs = 0
            var activeToday = 0
            var proUsers = 0
            var usersWithConcerts = 0
            var paidConcerts = 0
            var freeConcerts = 0
            var totalSpend = 0L
            var powerUsers = 0
            var active7d = 0
            var active30d = 0
            var usersWithSongs = 0
            var usersWithFirstSeen = 0
            val signups = HashMap<String, Int>()  // "yyyy/MM" → 新帳號
            val monthly = HashMap<String, Int>()  // "yyyy/MM" → 場次
            // 今日 00:00（Asia/Taipei）的 epoch millis
            val tz = kotlinx.datetime.TimeZone.of("Asia/Taipei")
            val today = kotlinx.datetime.Clock.System.now().toLocalDateTime(tz).date
            val startOfToday = LocalDateTime(today, LocalTime(0, 0))
                .toInstant(tz).toEpochMilliseconds()
            val nowMs = System.currentTimeMillis()
            users.forEach { u ->
                val last = (u.getLong("lastActiveAt") ?: u.getLong("lastBackupAt")) ?: 0L
                if (last >= startOfToday) activeToday++
                if (last >= nowMs - 7L * 24 * 60 * 60 * 1000) active7d++
                if (last >= nowMs - 30L * 24 * 60 * 60 * 1000) active30d++
                val firstSeen = u.getLong("firstSeenAt") ?: 0L
                if (firstSeen > 0L) {
                    usersWithFirstSeen++
                    val d = kotlinx.datetime.Instant.fromEpochMilliseconds(firstSeen)
                        .toLocalDateTime(tz).date
                    signups.merge("${d.year}/${d.monthNumber.toString().padStart(2, '0')}", 1, Int::plus)
                }
                if (u.getBoolean("isPro") == true) proUsers++
                val concerts = Tasks.await(u.reference.collection("concerts").get()).documents
                totalConcerts += concerts.size
                if (concerts.isNotEmpty()) usersWithConcerts++
                if (concerts.size >= 10) powerUsers++
                concerts.forEach { d ->
                    // 展開卡司再計次。音樂節那種「A / B / C / …」整串黏在 artistName
                    // 的紀錄，直接當 key 會變成排行榜上的一位「藝人」
                    // ——實機回報「掃描出來都是同一個藝人」就是這個。
                    com.bandary.domain.model.artistNamesForStats(d.getString("artistName"))
                        .forEach { name -> concertArtists.merge(name, 1, Int::plus) }
                    d.getString("city")?.takeIf { it.isNotBlank() }
                        ?.let { cities.merge(it.trim(), 1, Int::plus) }
                    val price = d.getDouble("ticketPrice") ?: 0.0
                    if (price > 0.0) { paidConcerts++; totalSpend += price.toLong() } else freeConcerts++
                    // 月趨勢：優先用 dateTime 字串前 7 碼 (yyyy-MM)，否則略過
                    (d.getString("dateTime") ?: d.getString("date"))?.takeIf { it.length >= 7 }?.let { dt ->
                        val ym = "${dt.substring(0, 4)}/${dt.substring(5, 7)}"
                        monthly.merge(ym, 1, Int::plus)
                    }
                }
                val ds = Tasks.await(u.reference.collection("daily_songs").get()).documents
                totalSongs += ds.size
                if (ds.isNotEmpty()) usersWithSongs++
                ds.forEach { d ->
                    val artist = d.getString("artistName").orEmpty().trim()
                    if (artist.isNotBlank()) songArtists.merge(artist, 1, Int::plus)
                    d.getString("songTitle")?.takeIf { it.isNotBlank() }?.let { t ->
                        songTitles.merge(if (artist.isBlank()) t.trim() else "${t.trim()} — $artist", 1, Int::plus)
                    }
                }
            }
            fun top(m: Map<String, Int>) =
                m.entries.sortedWith(compareByDescending<Map.Entry<String, Int>> { it.value }.thenBy { it.key })
                    .map { it.key to it.value }
            // 近 12 個月，依月份升冪
            val monthlyTrend = monthly.entries.sortedBy { it.key }.takeLast(12).map { it.key to it.value }
            GlobalStats(
                totalConcerts = totalConcerts,
                totalSongs = totalSongs,
                activeToday = activeToday,
                songArtistRanking = top(songArtists),
                songRanking = top(songTitles),
                concertArtistRanking = top(concertArtists),
                concertCityRanking = top(cities),
                scannedUsers = users.size,
                proUsers = proUsers,
                usersWithConcerts = usersWithConcerts,
                avgConcertsPerActiveUser = if (usersWithConcerts > 0) totalConcerts.toDouble() / usersWithConcerts else 0.0,
                paidConcerts = paidConcerts,
                freeConcerts = freeConcerts,
                totalSpend = totalSpend,
                powerUsers = powerUsers,
                monthlyConcertTrend = monthlyTrend,
                active7d = active7d,
                active30d = active30d,
                usersWithSongs = usersWithSongs,
                usersWithFirstSeen = usersWithFirstSeen,
                monthlySignupTrend = signups.entries.sortedBy { it.key }.takeLast(12).map { it.key to it.value }
            )
        }.onFailure { android.util.Log.w("FirestoreService", "globalStats failed", it) }
    }

