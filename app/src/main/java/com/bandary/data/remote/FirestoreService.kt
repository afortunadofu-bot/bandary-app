     * 所以兩個人同時加同一位藝人不會變成兩筆（同一份文件被寫兩次而已）。
     */
    suspend fun addArtist(name: String): Result<com.bandary.domain.model.ArtistEntry> =
        withContext(Dispatchers.IO) {
            val u = uid() ?: return@withContext Result.failure(IllegalStateException("要先登入才能新增藝人"))
            val clean = name.trim()
            if (clean.isBlank()) return@withContext Result.failure(IllegalArgumentException("藝人名不能是空白"))
            if (clean.length > 80) return@withContext Result.failure(IllegalArgumentException("藝人名太長"))
            val key = com.bandary.domain.model.artistFollowKey(clean)
            runCatching {
                val id = imageKey(key).take(24)
                val entry = com.bandary.domain.model.ArtistEntry(
                    id = id, name = clean, key = key, createdBy = u
                )
                Tasks.await(artistsCol().document(id).set(mapOf(
                    "name" to entry.name,
                    "key" to entry.key,
                    "aliases" to entry.aliases,
                    "createdBy" to u,
                    "createdAt" to entry.createdAt,
                    "verified" to false
                )))
                entry
            }.onFailure { android.util.Log.w("FirestoreService", "addArtist failed", it) }
        }

    /**
     * 一次性基底資料：把一批藝人名寫進資料庫（已經有的不覆寫）。
     * 回傳實際新增的筆數。只給管理員用：這是共用資料，一次灌幾百筆進去影響所有人。
     *
     * 名字只從**已核准的公開活動**來，不碰任何人的私人紀錄——
     * 把別人記在自己演唱會裡的東西默默發佈成公開資料不是應該做的事。
     */
    suspend fun seedArtists(names: List<String>): Result<Int> = withContext(Dispatchers.IO) {
        val u = uid() ?: return@withContext Result.failure(IllegalStateException("尚未登入"))
        runCatching {
            val existing = Tasks.await(artistsCol().get()).documents.mapNotNull { it.id }.toSet()
            val fresh = names.asSequence()
                .map { it.trim() }
                .filter { it.isNotBlank() && it.length <= 80 }
                .associateBy { imageKey(com.bandary.domain.model.artistFollowKey(it)).take(24) }
                .filterKeys { it !in existing }
            if (fresh.isEmpty()) return@runCatching 0
            commitBatched(
                fresh.map { (id, name) ->
                    { b: com.google.firebase.firestore.WriteBatch ->
                        b.set(artistsCol().document(id), mapOf(
                            "name" to name,
                            "key" to com.bandary.domain.model.artistFollowKey(name),
                            "aliases" to emptyList<String>(),
                            "createdBy" to u,
                            "createdAt" to System.currentTimeMillis(),
                            "verified" to false
                        ))
                    }
                }
            )
            fresh.size
        }.onFailure { android.util.Log.w("FirestoreService", "seedArtists failed", it) }
    }

    // ── 藝人合併 ──────────────────────────────────────────────
    //
    // 同一個團在資料庫裡有好幾種寫法（實機例子：ggteen / 公館青少年 / 公館青少年GGteen）。
    // 追蹤只追得到其中一種、排行把一個團拆成三份、統計怎麼看都不對。
    // 判斷規則見 [com.bandary.domain.model.ArtistMerge]。

    /**
     * 掃共用藝人資料庫，找出可以合併的組。只讀不寫，給管理員先看過再決定。
     *
     * [wiki] 有傳進來時會再跟中文維基核對每一組的正式名稱。
     * 維基查詢慢（每個名字最多三次請求、而且要間隔以免被擋），
     * 所以**只查每組的代表名**，不是每個寫法都查——
     * 同一組的寫法指的是同一個團，查一次就夠了。
     */
    suspend fun findArtistMergeGroups(
        wiki: WikipediaArtistService? = null
    ): Result<List<com.bandary.domain.model.ArtistMerge.Group>> =
        withContext(Dispatchers.IO) {
            runCatching {
                val names = fetchArtists().getOrDefault(emptyList()).map { it.name }
                val groups = com.bandary.domain.model.ArtistMerge.findGroups(names)
                if (wiki == null) return@runCatching groups
                groups.map { g ->
                    // 先問最長的那個（資訊最多、最可能命中條目）；
                    // 沒中再問其他寫法——英文別名常常才是維基收錄的那個。
                    val tried = listOf(g.canonical) + g.others
                    val hit = tried.firstNotNullOfOrNull { wiki.canonicalName(it) }
                    g.copy(wikiTitle = hit)
                }
            }
        }

    /**
     * 把一組寫法合併成 [canonical]。做三件事：
     *   1. 其他寫法存成 canonical 的 `aliases`——**不是直接丟掉**。
     *      別人可能是用舊寫法搜尋的，別名留著才搜得到。
     *   2. 刪掉其他寫法在 `artists` 裡的那幾筆。
     *   3. 把 `free_events` 卡司裡的舊寫法換成 canonical，並去掉因此重複的。
     *
     * **不動任何人的私人演唱會紀錄**：那是使用者自己的資料，
     * 他寫「公館青少年」就是他要的寫法，後台不該替他改掉。
     */
    suspend fun mergeArtists(
        group: com.bandary.domain.model.ArtistMerge.Group
    ): Result<Int> = withContext(Dispatchers.IO) {
        // 用 preferred：有維基資料就以維基的條目名稱為準。
        val canonical = group.preferred.trim()
        val others = group.others.map { it.trim() }.filter { it.isNotBlank() }
        if (canonical.isBlank() || others.isEmpty()) {
            return@withContext Result.failure(IllegalArgumentException("沒有可以合併的寫法"))
        }
        runCatching {
            val all = fetchArtists().getOrDefault(emptyList())
            // 維基給的正式名稱可能根本還不在資料庫裡（例如「滅火器樂團」），
            // 那就挑原本最長的那一筆來留，再把名字改成維基的寫法。
            val keep = all.firstOrNull { it.name.trim() == canonical }
                ?: all.firstOrNull { it.name.trim() == group.canonical.trim() }
            // 1 + 2：別名併進代表那一筆，其餘刪掉。
            if (keep != null) {
                val mergedAliases = (keep.aliases + others + keep.name).map { it.trim() }
                    .filter { it.isNotBlank() && it != canonical }
                    .distinct()
                Tasks.await(
                    db.collection("artists").document(keep.id).set(
                        // name 也要寫：維基的正式名稱可能跟原本那筆不一樣，
                        // 原本的名字會退成別名（上面的 mergedAliases 有帶 keep.name）。
                        mapOf("name" to canonical,
                              "key" to com.bandary.domain.model.artistFollowKey(canonical),
                              "aliases" to mergedAliases),
                        com.google.firebase.firestore.SetOptions.merge()
                    )
                )
            }
            all.filter { it.name.trim() in others }.forEach { dup ->
                runCatching { Tasks.await(db.collection("artists").document(dup.id).delete()) }
            }
            // 3：活動卡司換寫法。
            val groups = listOf(group)
            val docs = Tasks.await(db.collection("free_events").get()).documents
            var touched = 0
            var batch = db.batch()
            var inBatch = 0
            docs.forEach { d ->
                val raw = d.getString("artistName").orEmpty()
                if (raw.isBlank()) return@forEach
                val parts = com.bandary.domain.model.splitArtistNamesPasted(raw)
                if (parts.isEmpty()) return@forEach
                val applied = com.bandary.domain.model.ArtistMerge.applyTo(parts, groups)
                val next = applied.joinToString(" / ")
                if (next == raw) return@forEach
                batch.update(d.reference, mapOf("artistName" to next))
                touched++
                inBatch++
                if (inBatch >= 400) {
                    Tasks.await(batch.commit()); batch = db.batch(); inBatch = 0
                }
            }
            if (inBatch > 0) Tasks.await(batch.commit())
            touched
        }.onFailure { android.util.Log.w("FirestoreService", "mergeArtists failed", it) }
    }

