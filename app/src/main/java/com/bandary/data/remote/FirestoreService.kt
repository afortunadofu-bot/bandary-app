    /**
     * 讀取官方通知（最新在前）。
     *
     * **分兩段查**：全體公告（`targetUids` 是空陣列）與指定給我的
     * （`targetUids` array-contains 我的 uid）。
     * 不能一次抓完再在本機過濾——Firestore 的規則會擋掉「讀得到別人的公告」的查詢，
     * 而且那樣等於把別人收到什麼也下載到這台裝置上。
     *
     * 舊公告沒有 `targetUids` 欄位，查不到；所以第三段補一次「欄位不存在」的舊資料，
     * 不然升級之後以前的公告會全部消失。
     */
    suspend fun fetchAnnouncements(limit: Int = 50): Result<List<Announcement>> = withContext(Dispatchers.IO) {
        runCatching {
            val col = db.collection("announcements")
            fun parse(docs: List<com.google.firebase.firestore.DocumentSnapshot>) = docs.map { d ->
                Announcement(d.id, d.getString("title") ?: "", d.getString("body") ?: "", d.getLong("createdAt") ?: 0L, d.getString("createdBy"))
            }
            val public = runCatching {
                parse(Tasks.await(col.whereEqualTo("targetUids", emptyList<String>()).limit(limit.toLong()).get()).documents)
            }.getOrDefault(emptyList())
            val mine = uid()?.let { u ->
                runCatching {
                    parse(Tasks.await(col.whereArrayContains("targetUids", u).limit(limit.toLong()).get()).documents)
                }.getOrDefault(emptyList())
            }.orEmpty()
            // 升級前發的公告沒有 targetUids 欄位，兩段查詢都查不到它們。
            // 這裡**不另外補一段「全部抓下來」的查詢**——那種查詢在規則下必然被拒，
            // 而且就算放行，也等於把別人收到的公告下載到這台裝置上。
            // 正確作法是把舊資料補上欄位，見 backfillAnnouncementTargets()（管理員開後台時跑一次）。
            (public + mine)
                .distinctBy { it.id }
                .sortedByDescending { it.createdAt }
                .take(limit)
        }
    }

