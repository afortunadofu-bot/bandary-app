    /**
     * 手動觸發一次蒐集（callable `crawlNow`）。回傳可以直接顯示的摘要字串。
     *
     * 逾時放到 5 分鐘：雲端那支的 timeoutSeconds 就是 300，而且會開無頭瀏覽器，
     * 用預設的 70 秒等於每次都在使用者這邊逾時，實際上伺服器還在跑。
     */
    suspend fun runCrawlNow(): Result<String> = withContext(Dispatchers.IO) {
        runCatching {
            val res = Tasks.await(
                functions.getHttpsCallable("crawlNow")
                    .withTimeout(5, java.util.concurrent.TimeUnit.MINUTES)
                    .call()
            )
            val m = res.getData() as? Map<*, *> ?: return@runCatching "跑完了，但沒有回傳統計。"
            (m["note"] as? String)?.let { return@runCatching it }
            val sources = (m["sources"] as? Number)?.toInt() ?: 0
            val added = (m["added"] as? Number)?.toInt() ?: 0
            val skipped = (m["skipped"] as? Number)?.toInt() ?: 0
            "抓了 $sources 個來源：新增 $added 筆待審、略過 $skipped 筆。"
        }.onFailure { android.util.Log.w("FirestoreService", "crawlNow failed", it) }
    }

