    /**
     * 管理員審核。核准時一併把試用期寫進 promo_rewards/{uid}——
     * 分兩次寫會出現「標成已通過但沒發到試用期」的狀態，而且事後看不出是漏發還是沒發。
     *
     * 試用期採「從現在起算」或「接在既有試用期後面」取較晚者：
     * 連續兩次通過不該讓第二次把第一次剩下的天數吃掉。
     */
    suspend fun reviewPromo(
        submission: com.bandary.domain.model.PromoSubmission,
        approve: Boolean,
        comment: String
    ): Result<Unit> = withContext(Dispatchers.IO) {
        runCatching {
            val now = System.currentTimeMillis()
            val batch = db.batch()
            batch.update(
                promoCol().document(submission.id),
                mapOf(
                    "status" to (if (approve) com.bandary.domain.model.PromoStatus.APPROVED
                    else com.bandary.domain.model.PromoStatus.REJECTED).name,
                    "reviewComment" to comment.trim(),
                    "reviewedAt" to now
                )
            )
            if (approve) {
                val rewardRef = db.collection("promo_rewards").document(submission.uid)
                val existing = runCatching {
                    Tasks.await(rewardRef.get()).getLong("trialUntil") ?: 0L
                }.getOrDefault(0L)
                val base = maxOf(existing, now)
                val until = base + com.bandary.domain.model.PROMO_TRIAL_DAYS * 24L * 60 * 60 * 1000
                batch.set(rewardRef, mapOf(
                    "uid" to submission.uid,
                    "trialUntil" to until,
                    "grantedBy" to (currentEmail() ?: "admin"),
                    "grantedAt" to now,
                    "reason" to ("推廣任務通過：" + submission.platform)
                ), com.google.firebase.firestore.SetOptions.merge())
            }
            Tasks.await(batch.commit())
            Unit
        }
    }

