    /**
     * 記一次外站連結被點擊。[linkId] 見 [com.bandary.domain.model.OutboundLinks]。
     *
     * ## 這個數字是什麼、不是什麼
     * 它算的是**App 內那一列被點了幾次**，不是對方網站的瀏覽量，
     * 更不是下載數或贊助筆數——那些在別人的後台，我們拿不到。
     * 後台的標籤要照實寫，否則看到數字會以為有人真的裝了 / 贊助了。
     *
     * ## 隱私
     * 與 [touchGuestInstall] 同一套作法：只寫一組本機隨機 id、連結代號、次數、時間、版本。
     * **沒有 email、沒有 uid、沒有裝置識別碼**——誰點的不重要，有多少人點才重要。
     *
     * ## 文件 id 是 `{installId}_{linkId}`
     * 一人一連結一筆，所以「點過的安裝數」＝文件數、「總點擊」＝ taps 相加，
     * 兩個都算得出來。用巢狀 map 存各連結的次數也可以，但那樣 Firestore 規則
     * 就沒辦法驗「每次只能加一」——拆成一筆一文件才擋得住有人把數字灌到幾千。
     */
    suspend fun touchOutboundClick(linkId: String, installId: String, appVersion: String) =
        withContext(Dispatchers.IO) {
            if (installId.isBlank() || linkId.isBlank()) return@withContext
            runCatching {
                val ref = db.collection("outbound_clicks").document("${installId}_$linkId")
                val now = System.currentTimeMillis()
                val existing = runCatching { Tasks.await(ref.get()).getLong("firstAt") ?: 0L }.getOrDefault(0L)
                val data = mutableMapOf<String, Any>(
                    "link" to linkId,
                    "taps" to com.google.firebase.firestore.FieldValue.increment(1L),
                    "lastAt" to now,
                    "appVersion" to appVersion
                )
                if (existing <= 0L) data["firstAt"] = now
                Tasks.await(ref.set(data, com.google.firebase.firestore.SetOptions.merge()))
            }.onFailure { android.util.Log.w("FirestoreService", "touchOutboundClick failed", it) }
            Unit
        }

    /**
     * 一個外站連結的點擊統計。
     *
     * [installs] 是「點過的安裝數」、[taps] 是總點擊次數——兩個都給，因為差距本身有意義：
     * 10 個人各點一次，和 1 個人點了 10 次，對「要不要留這個入口」是完全不同的結論。
     */
    data class LinkClicks(
        val linkId: String = "",
        val installs: Int = 0,
        val taps: Int = 0,
        val installs7d: Int = 0
    )

    /** 全部外站連結的點擊統計（後台用）。回傳的 key 是 linkId。 */
    suspend fun outboundClickStats(): Result<Map<String, LinkClicks>> = withContext(Dispatchers.IO) {
        runCatching {
            val d7 = System.currentTimeMillis() - 7L * 24 * 60 * 60 * 1000
            val docs = Tasks.await(db.collection("outbound_clicks").get()).documents
            val installs = mutableMapOf<String, Int>()
            val taps = mutableMapOf<String, Int>()
            val recent = mutableMapOf<String, Int>()
            docs.forEach { d ->
                val link = d.getString("link") ?: return@forEach
                installs[link] = (installs[link] ?: 0) + 1
                taps[link] = (taps[link] ?: 0) + (d.getLong("taps") ?: 0L).toInt()
                if ((d.getLong("lastAt") ?: 0L) >= d7) recent[link] = (recent[link] ?: 0) + 1
            }
            installs.keys.associateWith { k ->
                LinkClicks(k, installs[k] ?: 0, taps[k] ?: 0, recent[k] ?: 0)
            }
        }.onFailure { android.util.Log.w("FirestoreService", "outboundClickStats failed", it) }
    }

