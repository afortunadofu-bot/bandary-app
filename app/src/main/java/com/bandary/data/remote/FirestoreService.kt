    /** Exchange the Google account's id token for a Firebase session. Returns email. */
    // Google Sign-In 整套已棄用，正式替代是 Credential Manager。
    // 那是會改到登入行為的遷移，必須單獨一批 + 實機驗證，不能併進「清警告」。
    // 在這裡標明決定，新出現的棄用才看得見。
    @Suppress("DEPRECATION")
    suspend fun signInWithIntent(data: Intent?): Result<String?> = withContext(Dispatchers.IO) {
        runCatching {
            val account = Tasks.await(com.google.android.gms.auth.api.signin.GoogleSignIn.getSignedInAccountFromIntent(data))
            val idToken = account.idToken ?: error("沒有 idToken，請確認已在 Firebase 啟用 Google 登入並重新下載 google-services.json")
            val cred = GoogleAuthProvider.getCredential(idToken, null)
            val result = Tasks.await(auth.signInWithCredential(cred))
            // 登入即登記 users/{uid}，讓後台可統計使用者人數 / 活躍時間（寫自己的文件，規則允許）。
            result.user?.uid?.let { u ->
                runCatching {
                    Tasks.await(
                        db.collection("users").document(u).set(
                            mapOf(
                                "email" to result.user?.email,
                                "lastActiveAt" to System.currentTimeMillis()
                            ),
                            com.google.firebase.firestore.SetOptions.merge()
                        )
                    )
                }
                // 第一次看到這個帳號的時間（只在還沒有值時寫）。分開寫而不是併進上面那個
                // map：那個 map 每次登入都會蓋，firstSeenAt 一旦被蓋成「最近一次登入」，
                // 它就失去意義了。
                ensureFirstSeen(u)
            }
            result.user?.email
        }
    }

    /** 後台使用者統計：總數 + 近 7 / 30 天活躍。需 Firestore 規則允許管理者讀取 users。 */
    data class UserSummary(val total: Int, val active7d: Int, val active30d: Int)

    suspend fun userStats(): Result<UserSummary> = withContext(Dispatchers.IO) {
        runCatching {
            val now = System.currentTimeMillis()
            val d7 = now - 7L * 24 * 60 * 60 * 1000
            val d30 = now - 30L * 24 * 60 * 60 * 1000
            val docs = Tasks.await(db.collection("users").get()).documents
            var a7 = 0; var a30 = 0
            docs.forEach { doc ->
                val last = (doc.getLong("lastActiveAt") ?: doc.getLong("lastBackupAt")) ?: 0L
                if (last >= d7) a7++
                if (last >= d30) a30++
            }
            UserSummary(total = docs.size, active7d = a7, active30d = a30)
        }
    }

    /**
     * 訪客（沒登入）的活躍紀錄。
     *
     * 為什麼需要：後台所有數字都建立在 `users/{uid}` 上，而那份文件只有**登入過**的人才有。
     * 也就是說「下載了、在用、但沒登入」的人，在後台完全是隱形的——
     * 漏斗最上層的「有帳號」看起來就是全部使用者，註冊轉換率永遠是 100%，
     * 這個數字沒有任何意義。
     *
     * 寫進 `guest_installs/{installId}`，**不含任何個人資料**：
     * 一組本機產生的隨機 id、第一次與最後一次開啟時間、App 版本。
     * 沒有 email、沒有裝置識別碼、不跨 App 追蹤。
     * 使用者登入之後這筆就不再更新（那時他已經出現在 users 裡，再算一次會重複）。
     *
     * installId 存在本機；重裝會變成新的一筆——所以這個數字是「安裝」不是「人」，
     * 後台的標籤也要照實寫成安裝數。
     */
    suspend fun touchGuestInstall(installId: String, appVersion: String) = withContext(Dispatchers.IO) {
        if (installId.isBlank()) return@withContext
        if (uid() != null) return@withContext   // 已登入的走 users，不要重複算
        runCatching {
            val ref = db.collection("guest_installs").document(installId)
            val now = System.currentTimeMillis()
            val existing = runCatching { Tasks.await(ref.get()).getLong("firstSeenAt") ?: 0L }.getOrDefault(0L)
            val data = mutableMapOf<String, Any>(
                "lastActiveAt" to now,
                "appVersion" to appVersion
            )
            if (existing <= 0L) data["firstSeenAt"] = now
            Tasks.await(ref.set(data, com.google.firebase.firestore.SetOptions.merge()))
        }.onFailure { android.util.Log.w("FirestoreService", "touchGuestInstall failed", it) }
        Unit
    }

