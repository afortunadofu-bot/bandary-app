    suspend fun repairLocalImages(concerts: List<Concert>): List<Concert> = withContext(Dispatchers.IO) {
        if (!isSignedIn()) return@withContext concerts
        val broken = concerts.filter { c -> c.allImageUris().any { !readableUri(it) } }
        if (broken.isEmpty()) return@withContext concerts
        val repairedById = materializeImages(broken).associateBy { it.id }
        concerts.map { repairedById[it.id] ?: it }
    }

