    /**
     * 把既有活動的 `artistName` 分隔符統一成 `" / "`。
     *
     * 為什麼需要：`FreeEvent.artistName` 的設計本來就是「一串卡司」，
     * 而 [com.bandary.domain.model.castLabel] 只認 `" / "` 當分隔。
     * 匯入進來的資料用的是 `、`、`｜`、沒空格的 `/` 等等，於是：
     *   - 嘉賓對不上主藝人（`guestsByArtist` 用名字當 key）
     *   - 排行要靠寬鬆比對才救得回來
     *
     * **只動分隔符與空白，不動任何名字**。正規化後跟原值一樣的不寫回，
     * 避免白白製造一次全集合的寫入。
     *
     * 回傳「改了幾筆 / 掃了幾筆」。
     */
    suspend fun normalizeEventArtists(): Result<Pair<Int, Int>> = withContext(Dispatchers.IO) {
        runCatching {
            val docs = Tasks.await(db.collection("free_events").get()).documents
            var changed = 0
            var batch = db.batch()
            var inBatch = 0
            docs.forEach { d ->
                val raw = d.getString("artistName").orEmpty()
                if (raw.isBlank()) return@forEach
                val names = com.bandary.domain.model.splitArtistNamesPasted(raw)
                if (names.isEmpty()) return@forEach
                val normalized = names.joinToString(" / ")
                if (normalized == raw) return@forEach
                batch.update(d.reference, mapOf("artistName" to normalized))
                changed++
                inBatch++
                // Firestore 一個 batch 最多 500 筆寫入，滿了就先送出去再開新的。
                if (inBatch >= 400) {
                    Tasks.await(batch.commit())
                    batch = db.batch()
                    inBatch = 0
                }
            }
            if (inBatch > 0) Tasks.await(batch.commit())
            changed to docs.size
        }.onFailure { android.util.Log.w("FirestoreService", "normalizeEventArtists failed", it) }
    }

