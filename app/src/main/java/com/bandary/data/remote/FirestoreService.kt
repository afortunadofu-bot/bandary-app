            val req = mapOf(
                "fromUid" to myUid,
                "fromHandle" to myHandle,
                "fromDisplayName" to currentDisplayName(),
                "fromEmail" to (currentEmail()?.lowercase() ?: ""),
                "createdAt" to System.currentTimeMillis()
            )
            Tasks.await(
                db.collection("users").document(target.uid)
                    .collection("friend_requests").document(myUid).set(req)
            )
            Unit
        }
    }

    /** 讀取收到的好友請求。 */
    suspend fun fetchFriendRequests(): Result<List<com.bandary.domain.model.FriendRequest>> = withContext(Dispatchers.IO) {
