        }
    }

    /** 以好友代碼搜尋使用者：handles/{小寫} → uid → shared_calendars/{uid}。 */
    suspend fun findByHandle(rawHandle: String): Result<SharedCalendar?> = withContext(Dispatchers.IO) {
        runCatching {
            val lower = rawHandle.trim().removePrefix("@").lowercase()
            if (lower.isBlank()) return@runCatching null
            val handleDoc = Tasks.await(db.collection("handles").document(lower).get())
            val targetUid = handleDoc.getString("uid") ?: return@runCatching null
            val calDoc = Tasks.await(db.collection("shared_calendars").document(targetUid).get())
            calDoc.data?.let(::sharedCalendarFromMap)
                ?: SharedCalendar(uid = targetUid, handle = handleDoc.getString("handle") ?: lower)
        }
    }

    /** 依 email 找對方（僅限對方已開放 email 搜尋者）。 */
    suspend fun findSharedCalendarByEmail(email: String): Result<SharedCalendar?> = withContext(Dispatchers.IO) {
        runCatching {
            val snap = Tasks.await(
                db.collection("shared_calendars")
                    .whereEqualTo("email", email.trim().lowercase())
                    .whereEqualTo("discoverableByEmail", true)
                    .limit(1).get()
            )
            snap.documents.firstOrNull()?.data?.let(::sharedCalendarFromMap)
        }
    }

    suspend fun fetchSharedCalendar(friendUid: String): Result<SharedCalendar?> = withContext(Dispatchers.IO) {
        runCatching {
            val doc = Tasks.await(db.collection("shared_calendars").document(friendUid).get())
            val card = doc.data ?: return@runCatching null
            // 內容在子文件；對方還沒用新版重新發布時子文件不存在，就退回名片裡的舊欄位（過渡期相容）。
            val payload = runCatching { Tasks.await(privatePayloadRef(friendUid).get()).data }.getOrNull()
            sharedCalendarFromMap(if (payload != null) card + payload else card)
        }
    }

    // ── 好友請求（雙向）─────────────────────────────────────────
    /** 送出好友請求：寫進對方的收件匣 users/{target}/friend_requests/{我}。 */
    suspend fun sendFriendRequest(target: SharedCalendar): Result<Unit> = withContext(Dispatchers.IO) {
        val myUid = uid() ?: return@withContext Result.failure(IllegalStateException("尚未登入"))
        if (target.uid == myUid) return@withContext Result.failure(IllegalArgumentException("不能加自己為好友"))
        runCatching {
