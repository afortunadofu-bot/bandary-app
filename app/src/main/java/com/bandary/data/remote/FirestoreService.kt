    // ── 爬蟲來源本體（crawl_sources）：**只有管理員碰得到** ────────────
    // 排程 crawlScheduled（每天台北 06:00）與 callable crawlNow 讀的都是這個集合。
    // 規則已經是 `allow read, write: if isAdmin()`，不需要再改規則。
    //
    // 為什麼 App 這邊要有這個畫面：雲端早就在每跑完一個來源寫 lastRunAt / lastCount，
    // 但 App 從來沒有讀過它——「上次什麼時候抓的、抓到幾筆」只能進 Firebase Console 看。
    // crawlNow 的註解甚至寫著「設定頁的『立即抓取』」，但那顆按鈕根本不存在。

    data class CrawlSource(
        val id: String = "",
        val url: String = "",
        val label: String = "",
        /** 空白＝自動判斷（先試 iCal / JSON-LD，再退回無頭瀏覽器）。 */
        val type: String = "",
        val active: Boolean = true,
        val lastRunAt: Long = 0L,
        val lastCount: Int = 0
    )

    private val functions by lazy {
        com.google.firebase.functions.FirebaseFunctions.getInstance("asia-east1")
    }

    suspend fun fetchCrawlSources(): Result<List<CrawlSource>> = withContext(Dispatchers.IO) {
        runCatching {
            Tasks.await(db.collection("crawl_sources").get()).documents.map { d ->
                val m = d.data.orEmpty()
                CrawlSource(
                    id = d.id,
                    url = m["url"] as? String ?: "",
                    label = m["label"] as? String ?: "",
                    type = m["type"] as? String ?: "",
                    // 沒寫 active 的舊文件當成啟用——排程查的是 active == true，
                    // 這裡顯示成「停用」會跟實際行為對不起來，反而誤導。
                    active = m["active"] as? Boolean ?: true,
                    lastRunAt = (m["lastRunAt"] as? Number)?.toLong() ?: 0L,
                    lastCount = (m["lastCount"] as? Number)?.toInt() ?: 0
                )
            }.sortedWith(compareByDescending<CrawlSource> { it.active }.thenBy { it.label.ifBlank { it.url } })
        }.onFailure { android.util.Log.w("FirestoreService", "fetchCrawlSources failed", it) }
    }

    /**
     * 新增或更新一個來源。id 空白＝新增。
     *
     * 不覆蓋 lastRunAt / lastCount：那兩個欄位是伺服器寫的，
     * 從這裡整份蓋回去會把紀錄洗掉，所以用 merge。
     */
    suspend fun saveCrawlSource(src: CrawlSource): Result<Unit> = withContext(Dispatchers.IO) {
        val clean = src.url.trim()
        if (!clean.startsWith("http://") && !clean.startsWith("https://")) {
            return@withContext Result.failure(IllegalArgumentException("網址要以 http:// 或 https:// 開頭"))
        }
        runCatching {
            val doc = if (src.id.isBlank()) db.collection("crawl_sources").document()
            else db.collection("crawl_sources").document(src.id)
            Tasks.await(doc.set(
                mapOf(
                    "url" to clean,
                    "label" to src.label.trim(),
                    "type" to src.type.trim(),
                    "active" to src.active
                ),
                com.google.firebase.firestore.SetOptions.merge()
            ))
            Unit
        }.onFailure { android.util.Log.w("FirestoreService", "saveCrawlSource failed", it) }
    }

